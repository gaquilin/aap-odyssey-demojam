#!/usr/bin/env bash
set -euo pipefail
CSV=$(oc get csv -n nvidia-gpu-operator -o name | grep gpu-operator-certified | head -1)
[ -n "$CSV" ] || { echo "GPU Operator CSV not found: run step 1.2 first" >&2; exit 1; }
OUT="$(cd "$(dirname "$0")" && pwd)/clusterpolicy.yaml"
oc get "$CSV" -n nvidia-gpu-operator -o jsonpath='{.metadata.annotations.alm-examples}' \
  | jq '.[] | select(.kind == "ClusterPolicy")' \
  | oc create --dry-run=client -o yaml -f - \
  | { echo "# ClusterPolicy = default example of ${CSV#*/} (alm-examples), generated by 02-clusterpolicy.sh"; cat; } > "$OUT"
echo "Written $OUT (from $CSV):"
grep -E '^  name:|^    enabled:' "$OUT" | head -5 || true
if [ "${1:-}" = "--apply" ]; then
  oc apply -f "$OUT"
else
  echo "Review it, then: oc apply -f $OUT"
fi
