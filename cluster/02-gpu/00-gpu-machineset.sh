#!/usr/bin/env bash
set -euo pipefail

INSTANCE_TYPE="${INSTANCE_TYPE:-g6.2xlarge}"
ROOT_GB="${ROOT_GB:-200}"
OUT="$(cd "$(dirname "$0")" && pwd)/gpu-machineset.yaml"
NS=openshift-machine-api

command -v jq >/dev/null || { echo "jq is required" >&2; exit 1; }

echo "Worker machine sets:"
oc -n "$NS" get machinesets
SOURCE="${SOURCE:-$(oc -n "$NS" get machinesets -o json \
  | jq -r '[.items[] | select(.metadata.name | test("-worker-")) | select((.spec.replicas // 0) > 0)][0].metadata.name')}"
[ -n "$SOURCE" ] && [ "$SOURCE" != "null" ] || { echo "No worker machine set found: set SOURCE=<name>" >&2; exit 1; }
NEW="${SOURCE/-worker-/-gpu-}"
[ "$NEW" != "$SOURCE" ] || NEW="${SOURCE}-gpu"
echo "Copying $SOURCE -> $NEW ($INSTANCE_TYPE, root disk ${ROOT_GB} GiB)"

oc -n "$NS" get machineset "$SOURCE" -o json | jq --arg new "$NEW" --arg type "$INSTANCE_TYPE" --argjson gb "$ROOT_GB" '
  del(.status, .metadata.uid, .metadata.resourceVersion, .metadata.creationTimestamp, .metadata.generation,
      .metadata.annotations, .metadata.managedFields)
  | .metadata.name = $new
  | .spec.replicas = 1
  | .spec.selector.matchLabels["machine.openshift.io/cluster-api-machineset"] = $new
  | .spec.template.metadata.labels["machine.openshift.io/cluster-api-machineset"] = $new
  | .spec.template.spec.providerSpec.value.instanceType = $type
  | (.spec.template.spec.providerSpec.value.blockDevices[0].ebs.volumeSize) = $gb
  | .spec.template.spec.metadata.labels["node-role.kubernetes.io/gpu"] = ""
' | oc create --dry-run=client -o yaml -f - \
  | { echo "# GPU MachineSet generated by cluster/02-gpu/00-gpu-machineset.sh from $SOURCE"; \
      echo "# Changes: name, machineset labels, instanceType $INSTANCE_TYPE, root disk ${ROOT_GB} GiB, node label gpu"; \
      cat; } > "$OUT"

echo "Written $OUT. Differences from $SOURCE:"
diff <(oc -n "$NS" get machineset "$SOURCE" -o yaml | grep -vE '^\s*(uid|resourceVersion|creationTimestamp|generation):') \
     <(grep -v '^#' "$OUT") || true

if [ "${1:-}" = "--create" ]; then
  oc create -f "$OUT"
  echo "Created. Wait for: oc -n $NS get machines | grep gpu   -> Running"
else
  echo "Review the file, then: oc create -f $OUT"
fi
